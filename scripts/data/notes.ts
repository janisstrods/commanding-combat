// Generated sections of design/data-notes.md: the text between `<!-- auto:<name> -->` and `<!-- /auto:<name> -->`
// is rewritten by every build; everything else in the file is hand-written.
import { readFileSync, writeFileSync } from 'node:fs';

export function updateNotesSection(path: string, name: string, title: string, lines: string[]): boolean {
  const open = `<!-- auto:${name} -->`;
  const close = `<!-- /auto:${name} -->`;
  const body = `${open}\n## ${title}\n\n_Generated by scripts/build-data.ts; edit the build, not this section._\n\n${lines.join('\n')}\n${close}`;
  const old = readFileSync(path, 'utf8');
  const i = old.indexOf(open);
  const j = old.indexOf(close);
  const next = i >= 0 && j > i ? old.slice(0, i) + body + old.slice(j + close.length) : `${old.trimEnd()}\n\n${body}\n`;
  if (next === old) return false;
  writeFileSync(path, next);
  return true;
}
