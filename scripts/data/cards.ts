// design/data/fate-cards.json → src/data/cards.json (FateCard shape, Random Hex kept as a label like "A3").
import { parseHex } from '../../src/engine/hex';
import type { ActionName, EventName, Nation, OrderName, Trigger } from '../../src/engine/types';
import { ACTION_NAMES, EVENT_NAMES, NATIONS, ORDER_NAMES, normalise } from './names';

export interface CardJson {
  id: string;
  nation: Nation;
  number: number;
  order: OrderName;
  fireIsAction: boolean;
  action: ActionName;
  defenderOnly: boolean;
  event: EventName;
  white: number;
  red: number;
  trigger: Trigger | null;
  hex: string;
  breeze: number | null;
}

const PREFIX: Record<Nation, string> = { German: 'G', American: 'A', Russian: 'R' };
const TRIGGERS = ['Event', 'Jammed', 'Sniper', 'Time'];

/** §A27, §A35: Bore Sighting and the Hidden actions are scenario-Defender only. */
const defenderOnlyByRule = (a: ActionName) => a === 'Bore Sighting' || a.startsWith('Hidden ');

export function buildCards(src: any): { _source: string; _notes: string[]; cards: CardJson[] } {
  const cards: CardJson[] = [];
  for (const nation of NATIONS) {
    const deck: any[] = src.decks[nation];
    if (!deck || deck.length !== 72) throw new Error(`${nation} deck: expected 72 cards`);
    for (const c of deck) {
      const id = `${PREFIX[nation]}-${String(c.number).padStart(2, '0')}`;
      const order = normalise(c.order, ORDER_NAMES, 'order');
      const action = normalise(c.action, ACTION_NAMES, 'action');
      const event = normalise(c.event, EVENT_NAMES, 'event');
      const defenderOnly = defenderOnlyByRule(action);
      if (Boolean(c.action_defender_only) !== defenderOnly) {
        throw new Error(`${id}: action_defender_only=${c.action_defender_only} disagrees with the rules for ${action}`);
      }
      const trigger = c.trigger === null || c.trigger === 'None' ? null : c.trigger;
      if (trigger !== null && !TRIGGERS.includes(trigger)) throw new Error(`${id}: unknown trigger ${c.trigger}`);
      parseHex(c.random_hex); // throws on a bad label
      const breeze = c.breeze_direction ?? null;
      if ((breeze !== null) !== (event === 'Breeze')) throw new Error(`${id}: breeze direction only on Breeze cards`);
      cards.push({
        id,
        nation,
        number: c.number,
        order,
        fireIsAction: order === 'Fire' && Boolean(c.order_also_playable_as_action),
        action,
        defenderOnly,
        event,
        white: c.dice.white,
        red: c.dice.red,
        trigger,
        hex: c.random_hex,
        breeze,
      });
    }
  }
  return {
    _source: 'Generated by scripts/build-data.ts from design/data/fate-cards.json (VASSAL module 2.6.4 card layers). Do not edit by hand.',
    _notes: [
      'ids: G = German deck, A = American deck, R = Russian deck (the module calls the Russian cards S-nn).',
      'Names use the src/engine/types.ts spellings (White Phosphorus, Medic, Elan).',
      'fireIsAction: "Order/Action Fire" cards, playable as the Fire Order, as Op Fire, or for their printed Action.',
      'defenderOnly: Bore Sighting and the Hidden actions (scenario Defender only, rules-reference A27/A35).',
      'hex: the printed Random Hex label; breeze: wind direction 1..6 on the six Breeze cards, null on the rest.',
    ],
    cards,
  };
}
